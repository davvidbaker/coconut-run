export function groundHeight(points, x) {
  for (let i = 0; i < points.length - 1; i++) {
    const a = points[i],
      b = points[i + 1];
    if (x >= a[0] && x <= b[0])
      return a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0]);
  }
  return 1000;
}

export function medal(cargo, time, gold) {
  return cargo === 15 && time <= gold
    ? "gold"
    : cargo >= 12
      ? "silver"
      : cargo >= 6
        ? "bronze"
        : "try again";
}
